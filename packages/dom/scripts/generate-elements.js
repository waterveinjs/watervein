import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const elementsPath = resolve(packageDir, 'scripts/elements.json');
const outputPath = resolve(packageDir, 'src/elements.ts');
const elements = JSON.parse(readFileSync(elementsPath, 'utf8'));

if (!Array.isArray(elements) || elements.length === 0) {
  throw new Error('The elements list must be a non-empty array.');
}

const names = new Set();
const tags = new Set();

for (const entry of elements) {
  if (
    entry === null ||
    typeof entry !== 'object' ||
    typeof entry.name !== 'string' ||
    typeof entry.tag !== 'string' ||
    !/^[A-Za-z_$][\w$]*$/.test(entry.name) ||
    !/^[a-z][a-z0-9-]*$/.test(entry.tag)
  ) {
    throw new Error(`Invalid element entry: ${JSON.stringify(entry)}`);
  }

  if (names.has(entry.name)) {
    throw new Error(`Duplicate export name: ${entry.name}`);
  }
  if (tags.has(entry.tag)) {
    throw new Error(`Duplicate HTML tag: ${entry.tag}`);
  }

  names.add(entry.name);
  tags.add(entry.tag);
}

const generated = [
  '// This file is generated by scripts/generate-elements.js. Do not edit it directly.',
  '',
  "import { element } from '@watervein/dom-core';",
  '',
  ...elements.map(
    ({ name, tag }) =>
      `export const ${name} = (props?: any, children?: any) => element("${tag}", props, children);`,
  ),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current;
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  if (current !== generated) {
    console.error('packages/dom/src/elements.ts is out of date. Run "pnpm --filter @watervein/dom generate".');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
}
